//! Huffman decoding of HPACK header strings (ngx_http_huff_decode.c).
//!
//! A nibble-at-a-time automaton over RFC 7541 Appendix B. CODES was
//! generated from the C source by scripts/gen_huff.py and must stay identical
//! to it: nginx accepts padding longer than 7 bits (all ones) because of how
//! these states end, and HTTP/2 clients rely on that.

use ngx_core::log::{Log, NGX_LOG_DEBUG_HTTP};
use ngx_core::ngx_log_debug;

/// ngx_http_huff_decode_code_t
#[derive(Clone, Copy)]
struct Code {
    next: u8,
    emit: u8,
    sym: u8,
    ending: u8,
}

const fn c(next: u8, emit: u8, sym: u8, ending: u8) -> Code {
    Code { next, emit, sym, ending }
}

/// ngx_http_huff_decode: decode `src`, appending to `dst`. `state` carries the
/// automaton across calls for a string split over several buffers and must be
/// 0 at the start of a string. With `last`, a string ending inside a code is an
/// error, and `state` is reset.
pub fn huff_decode(state: &mut u8, src: &[u8], dst: &mut Vec<u8>, last: bool, log: &Log) -> Result<(), ()> {
    let mut ch = 0u8;
    let mut ending = 1u8;

    for &b in src {
        ch = b;

        if decode_bits(state, &mut ending, ch >> 4, dst).is_err() {
            ngx_log_debug!(NGX_LOG_DEBUG_HTTP, log, "http huffman decoding error at state {}: bad code 0x{:X}", *state, ch >> 4);
            return Err(());
        }

        if decode_bits(state, &mut ending, ch & 0xf, dst).is_err() {
            ngx_log_debug!(NGX_LOG_DEBUG_HTTP, log, "http huffman decoding error at state {}: bad code 0x{:X}", *state, ch & 0xf);
            return Err(());
        }
    }

    if last {
        if ending == 0 {
            ngx_log_debug!(NGX_LOG_DEBUG_HTTP, log, "http huffman decoding error: incomplete code 0x{:X}", ch);
            return Err(());
        }

        *state = 0;
    }

    Ok(())
}

/// ngx_http_huff_decode_bits
#[inline]
fn decode_bits(state: &mut u8, ending: &mut u8, bits: u8, dst: &mut Vec<u8>) -> Result<(), ()> {
    let code = CODES[*state as usize][bits as usize];

    if code.next == *state {
        return Err(());
    }

    if code.emit != 0 {
        dst.push(code.sym);
    }

    *ending = code.ending;
    *state = code.next;

    Ok(())
}

